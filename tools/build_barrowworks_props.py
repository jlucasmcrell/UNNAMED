def flat_material(name, colour):
    image = bpy.data.images.new(name+'_colour',width=4,height=4)
    image.pixels = list(colour)*16
    image.pack()
    material = bpy.data.materials.new(name)
    material.use_nodes = True
    nodes = material.node_tree.nodes
    tex = nodes.new('ShaderNodeTexImage')
    tex.image = image
    bsdf = nodes.get('Principled BSDF')
    material.node_tree.links.new(tex.outputs['Color'],bsdf.inputs['Base Color'])
    bsdf.inputs['Roughness'].default_value = .87
    return material

worn_metals={}
def worn_metal(source):
    if source.name in worn_metals:return worn_metals[source.name]
    material=source.copy();material.name='worn_iron_'+source.name
    bsdf=material.node_tree.nodes.get('Principled BSDF')
    # Remove modern blue/red paint while retaining the owned scan's wear/roughness/normal detail.
    for link in bsdf.inputs['Base Color'].links:
        if link.from_node.type=='TEX_IMAGE' and link.from_node.image:
            image=link.from_node.image.copy()
            pixels=np.asarray(image.pixels[:],dtype=np.float32).reshape(-1,4)
            luma=pixels[:,:3]@np.array([.2126,.7152,.0722],dtype=np.float32)
            pixels[:,:3]=luma[:,None]*np.array([.64,.59,.50])+np.array([.025,.018,.011])
            image.pixels.foreach_set(pixels.ravel());image.pack();link.from_node.image=image
    bsdf.inputs['Metallic'].default_value=.6;bsdf.inputs['Roughness'].default_value=.76
    worn_metals[source.name]=material
    return material

