def gear(name, at, radius, teeth):
    # Hand-built open spur gear: toothed rim, spokes and axle; no generated mesh service.
    verts=[];faces=[];count=teeth*4
    for x in (-.065,.065):
        for inner in (False,True):
            for i in range(count):
                angle=2*math.pi*i/count
                r=radius*.64 if inner else radius*(1 if i%4 in (1,2) else .88)
                verts.append((x,r*math.cos(angle),r*math.sin(angle)))
    for i in range(count):
        j=(i+1)%count
        faces.extend([(i,j,count+j,count+i),(2*count+i,3*count+i,3*count+j,2*count+j),
            (i,2*count+i,2*count+j,j),(count+i,count+j,3*count+j,3*count+i)])
    mesh=bpy.data.meshes.new(name);mesh.from_pydata(verts,[],faces);mesh.materials.append(iron)
    obj=bpy.data.objects.new(name,mesh);bpy.context.collection.objects.link(obj);obj.location=at
    parts=[obj,cylinder('keyed_axle',at,.13,.35,brass)]
    for angle in (0,math.pi/3,2*math.pi/3):
        spoke=box('cast_spoke',at,(.10,radius*1.6,.10),iron);spoke.rotation_euler.x=angle;parts.append(spoke)
    bpy.ops.object.select_all(action='DESELECT')
    for part in parts:part.select_set(True)
    bpy.context.view_layer.objects.active=obj;bpy.ops.object.join()
    return obj

