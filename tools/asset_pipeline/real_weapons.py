"""Build the real (non-generative) weapons as game-ready GLBs: scale, pivot, LODs, 2K textures, grip and carry sockets.

Run under Blender:
    blender -b -P real_weapons.py -- <out_dir> <weapon id> [<weapon id> ...]
    blender -b -P real_weapons.py -- <out_dir> all

Sources (all owned or CC0; nothing here was generated by an AI model):
    cos_sword, cos_sheath, cos_axe, cos_knife   Cosmos premium photogrammetry (MVV SwordSet, MVV Axe, ADA Knife), unzipped to SRC
    estoc, kite_shield                          Poly Haven (CC0) models
    spear, longbow, quiver                      modelled here from real-world proportions with Poly Haven CC0 textures

A weapon GLB is Y-up, one mesh node named after the asset with its origin at the butt (pommel / spear butt / bow's lower tip),
long axis +Y, edge or guard along glTF Z, flat along glTF X; sockets are sibling nodes rotated (0.5, 0.5, 0.5, 0.5), which sends
the socket's +X (the primary axis the game reads) along the weapon toward its head and its +Y along glTF +Z.
"""
