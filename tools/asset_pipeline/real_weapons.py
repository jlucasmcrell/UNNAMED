# Sockets are stored as (name, position along the long axis in metres, offset in blender (x, y)); orientation is fixed (see docstring).
SOCKET_BASIS = Matrix(((0, 0, 1), (0, -1, 0), (1, 0, 0))).transposed()  # columns: +X->Z(up), +Y->-Y (glTF +Z), +Z->X


def reset():
    bpy.ops.wm.read_factory_settings(use_empty=True)


def scale_image(img, px):
    if max(img.size) > px:
        img.scale(px, px) if img.size[0] == img.size[1] else img.scale(px, max(1, int(img.size[1] * px / img.size[0])))


def adjust_image(img, scale=1.0, channel=None, cap=None):
    """Edit pixels in place: multiply colour by `scale` (clamped), or cap one channel (2 = B, the metal channel of an ORM pack)."""
    import numpy as np
    n = len(img.pixels)
    a = np.empty(n, dtype=np.float32)
    img.pixels.foreach_get(a)
    a = a.reshape(-1, 4)
    if channel is not None:
        a[:, channel] = np.minimum(a[:, channel], cap)
    if scale != 1.0:
        a[:, :3] = np.clip(a[:, :3] * scale, 0, 1)
    img.pixels.foreach_set(a.reshape(-1))
    img.update()


# Godot draws a full-metal surface with only the sky for it to reflect, so scanned steel reads black: the shipped weapons cap the
# metal channel and lift the albedo a little (the earlier sword was the same fault: "a thin black stick").
METAL_CAP = 0.22
ALBEDO_LIFT = 1.55


def make_material(name, base, orm=None, normal=None, px=2048, tint=None, uv_scale=None, lift=1.0, metal_cap=None):
    """Principled material from image files. `orm` is a glTF-style pack (R occlusion, G roughness, B metal)."""
    mat = bpy.data.materials.new(name)
    mat.use_nodes = True
    nt = mat.node_tree
    for n in list(nt.nodes):
        if n.type != "OUTPUT_MATERIAL":
            nt.nodes.remove(n)
    out = next(n for n in nt.nodes if n.type == "OUTPUT_MATERIAL")
    bsdf = nt.nodes.new("ShaderNodeBsdfPrincipled")
    nt.links.new(bsdf.outputs["BSDF"], out.inputs["Surface"])
    coord = None
    if uv_scale:
        coord = nt.nodes.new("ShaderNodeTexCoord")
        mapping = nt.nodes.new("ShaderNodeMapping")
        mapping.inputs["Scale"].default_value = (uv_scale[0], uv_scale[1], 1)
        nt.links.new(coord.outputs["UV"], mapping.inputs["Vector"])

    def tex(path, cs):
        img = bpy.data.images.load(path, check_existing=False)
        scale_image(img, px)
        img.colorspace_settings.name = cs
        node = nt.nodes.new("ShaderNodeTexImage")
        node.image = img
        if coord:
            nt.links.new(mapping.outputs["Vector"], node.inputs["Vector"])
        return node

    b = tex(base, "sRGB")
    if lift != 1.0:
        adjust_image(b.image, scale=lift)
    if tint:
        mix = nt.nodes.new("ShaderNodeMix")
        mix.data_type = "RGBA"
        mix.blend_type = "MULTIPLY"
        mix.inputs["Factor"].default_value = 1.0
        mix.inputs["B"].default_value = tint
        nt.links.new(b.outputs["Color"], mix.inputs["A"])
        nt.links.new(mix.outputs["Result"], bsdf.inputs["Base Color"])
    else:
        nt.links.new(b.outputs["Color"], bsdf.inputs["Base Color"])
    if orm:
        o = tex(orm, "Non-Color")
        if metal_cap is not None:
            adjust_image(o.image, channel=2, cap=metal_cap)
        sep = nt.nodes.new("ShaderNodeSeparateColor")
        nt.links.new(o.outputs["Color"], sep.inputs["Color"])
        nt.links.new(sep.outputs["Green"], bsdf.inputs["Roughness"])
        nt.links.new(sep.outputs["Blue"], bsdf.inputs["Metallic"])
    if normal:
        n = tex(normal, "Non-Color")
        nm = nt.nodes.new("ShaderNodeNormalMap")
        nt.links.new(n.outputs["Color"], nm.inputs["Color"])
        nt.links.new(nm.outputs["Normal"], bsdf.inputs["Normal"])
    return mat


def ph_tex(set_name, px=2048, tint=None, uv_scale=None, metal=False):
    d = os.path.join(PH, "textures", set_name)
    f = lambda s: os.path.join(d, f"{set_name}_{s}_4k.jpg")
    diff = f("diff") if os.path.exists(f("diff")) else f("albedo")
    return make_material("MAT_" + set_name, diff, f("arm"), f("nor_gl"), px, tint, uv_scale)


def plain_pbr(name, colour, metallic, roughness):
    """A flat PBR material (no image): forged iron has no photographic texture here, only colour, metal and roughness."""
    mat = bpy.data.materials.new(name)
    mat.use_nodes = True
    b = next(n for n in mat.node_tree.nodes if n.type == "BSDF_PRINCIPLED")
    b.inputs["Base Color"].default_value = colour
    b.inputs["Metallic"].default_value = metallic
    b.inputs["Roughness"].default_value = roughness
    return mat


def bounds(obj):
    mw = obj.matrix_world
    pts = [mw @ v.co for v in obj.data.vertices]  # bound_box is stale after data.transform
    return Vector([min(v[i] for v in pts) for i in range(3)]), Vector([max(v[i] for v in pts) for i in range(3)])


def apply_all(obj):
    bpy.context.view_layer.objects.active = obj
    for o in bpy.context.selected_objects:
        o.select_set(False)
    obj.select_set(True)
    bpy.ops.object.transform_apply(location=True, rotation=True, scale=True)


def join_meshes(name, meshes=None):
    meshes = meshes or [o for o in bpy.data.objects if o.type == "MESH"]
    for o in bpy.context.selected_objects:
        o.select_set(False)
    for o in meshes:
        o.select_set(True)
        o.parent = None
    bpy.context.view_layer.objects.active = meshes[0]
    bpy.ops.object.join()
    obj = bpy.context.view_layer.objects.active
    obj.name = name
    obj.data.name = name + "_mesh"
    apply_all(obj)
    return obj


def transform_mesh(obj, matrix):
    obj.data.transform(matrix)
    obj.data.update()


def triangulate(obj):
    bm = bmesh.new()
    bm.from_mesh(obj.data)
    bmesh.ops.triangulate(bm, faces=bm.faces[:])
    bm.to_mesh(obj.data)
    bm.free()


def decimate_to(obj, tris):
    triangulate(obj)
    n = len(obj.data.polygons)
    if n <= tris:
        return n
    mod = obj.modifiers.new("dec", "DECIMATE")
    mod.ratio = tris / n
    bpy.context.view_layer.objects.active = obj
    bpy.ops.object.modifier_apply(modifier=mod.name)
    return len(obj.data.polygons)


def orient_long_axis_up(obj, scale=1.0):
    """Long axis -> +Z, butt at z=0 (sorted so the wider end, a pommel or guard, is at the bottom), centred on x/y of the lowest 15 %."""
    lo, hi = bounds(obj)
    ext = hi - lo
    axis = max(range(3), key=lambda i: ext[i])
    m = Matrix.Identity(4)
    if axis == 0:
        m = Matrix.Rotation(math.radians(-90), 4, "Y")  # +X -> +Z
    elif axis == 1:
        m = Matrix.Rotation(math.radians(90), 4, "X")  # +Y -> +Z
    transform_mesh(obj, m)
    transform_mesh(obj, Matrix.Scale(scale, 4))
    lo, hi = bounds(obj)
    transform_mesh(obj, Matrix.Translation((0, 0, -lo.z)))
    return obj


def widest_slice_z(obj, axis, lo_frac=0.0, hi_frac=1.0, bins=80):
    """z (along +Z) of the slice with the greatest extent along `axis` (0=x, 1=y), within a fraction of the length."""
    lo, hi = bounds(obj)
    L = hi.z - lo.z
    mins = [1e9] * bins
    maxs = [-1e9] * bins
    for v in obj.data.vertices:
        b = min(bins - 1, max(0, int((v.co.z - lo.z) / L * bins)))
        mins[b] = min(mins[b], v.co[axis])
        maxs[b] = max(maxs[b], v.co[axis])
    best = max(range(int(lo_frac * bins), int(hi_frac * bins)), key=lambda b: maxs[b] - mins[b])
    return lo.z + (best + 0.5) / bins * L


def flip_if_guard_high(obj, axis):
    """If the widest feature sits in the upper half, the weapon is upside down for our convention: turn it over."""
    lo, hi = bounds(obj)
    zg = widest_slice_z(obj, axis)
    if zg > (lo.z + hi.z) / 2:
        transform_mesh(obj, Matrix.Rotation(math.pi, 4, "X"))
        lo, hi = bounds(obj)
        transform_mesh(obj, Matrix.Translation((0, 0, -lo.z)))


def centre_xy_on_axis(obj, z0, z1):
    sel = [v.co for v in obj.data.vertices if z0 <= v.co.z <= z1]
    cx = sum(v.x for v in sel) / len(sel)
    cy = sum(v.y for v in sel) / len(sel)
    transform_mesh(obj, Matrix.Translation((-cx, -cy, 0)))


def add_socket(name, z, x=0.0, y=0.0, parent=None):
    e = bpy.data.objects.new(name, None)
    e.empty_display_type = "ARROWS"
    e.empty_display_size = 0.05
    bpy.context.scene.collection.objects.link(e)
    e.matrix_world = Matrix.Translation((x, y, z)) @ SOCKET_BASIS.to_4x4()
    return e


def export(obj, asset_id, sockets, lod_tris, tex_px, meta):
    """Export the full asset and its LODs; returns the metadata record."""
    os.makedirs(os.path.join(OUT, asset_id), exist_ok=True)
    tri0 = len(obj.data.polygons)  # polygons before triangulation
    records = []
    for i, (tris, px) in enumerate(zip(lod_tris, tex_px)):
        work = obj.copy()
        work.data = obj.data.copy()
        bpy.context.scene.collection.objects.link(work)
        work.name = asset_id if i == 0 else f"{asset_id}_lod{i}"
        work.data.name = work.name + "_mesh"
        n = decimate_to(work, tris) if tris else (triangulate(work), len(work.data.polygons))[1]
        # materials: scale a private copy of each image for this LOD
        for slot in work.material_slots:
            mat = slot.material.copy()
            mat.name = slot.material.name + (f"_lod{i}" if i else "")
            for node in mat.node_tree.nodes:
                if node.type == "TEX_IMAGE" and node.image:
                    img = node.image.copy()
                    img.name = node.image.name + f"_{px}"
                    scale_image(img, px)
                    node.image = img
            slot.material = mat
        for o in bpy.context.selected_objects:
            o.select_set(False)
        work.select_set(True)
        objs = [work]
        if i == 0:
            for s in sockets:
                s.select_set(True)
                objs.append(s)
        bpy.context.view_layer.objects.active = work
        path = os.path.join(OUT, asset_id, (asset_id if i == 0 else f"{asset_id}_lod{i}") + ".glb")
        bpy.ops.export_scene.gltf(
            filepath=path, export_format="GLB", use_selection=True, export_apply=True, export_yup=True,
            export_image_format="JPEG", export_jpeg_quality=88, export_materials="EXPORT", export_texcoords=True,
            export_normals=True, export_cameras=False, export_lights=False)
        records.append({"lod": i, "file": os.path.basename(path), "triangles": n, "texture_px": px, "bytes": os.path.getsize(path)})
    lo, hi = bounds(obj)
    rec = dict(meta, asset_id=asset_id, category="weapon", triangles_lod0=records[0]["triangles"], lods=records,
               dimensions_m={"glb_x": round(hi.x - lo.x, 3), "glb_y": round(hi.z - lo.z, 3), "glb_z": round(hi.y - lo.y, 3)},
               units="metres, 1 unit = 1 m", glb_axes="Y-up; origin at the butt; long axis +Y; guard/edge along Z; flat along X",
               sockets={s.name: {"y_m": round(s.matrix_world.translation.z, 4), "x_m": round(s.matrix_world.translation.x, 4),
                                 "z_m": round(-s.matrix_world.translation.y, 4),
                                 "primary": "+Y (toward the head)", "secondary": "+Z"} for s in sockets},
               source_tris_before=tri0)
    with open(os.path.join(OUT, asset_id, asset_id + "_meta.json"), "w") as f:
        json.dump(rec, f, indent=1)
    return rec


