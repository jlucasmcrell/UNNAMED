def import_fbx(path):
    before = set(bpy.data.objects)
    bpy.ops.import_scene.fbx(filepath=path)
    new = [o for o in bpy.data.objects if o not in before and o.type == "MESH"]
    return join_meshes("tmp", new) if len(new) > 1 else (apply_all(new[0]) or new[0])


SWORD_SCALE = 1.2  # the scanned sword is 0.744 m overall; the arming sword the game wants is ~0.9 m (1.2 -> 0.89 m)


def build_cos_sword():
    reset()
    o = import_fbx(os.path.join(SRC, "MVV_SwordSet_Sword", "MVV_SwordSet_Sword", "Meshes", "SM_MVV_Sword_c0_LOD0.fbx"))
    o.name = "weapon_real_arming_sword"
    return finish_cos_sword(o, with_sheath=False)


def finish_cos_sword(o, with_sheath):
    # cm FBX is imported at scale 0.01 -> metres. Sword long axis is already +Z, guard along X: turn the guard onto Y
    orient_long_axis_up(o, SWORD_SCALE)
    flip_if_guard_high(o, 0)
    transform_mesh(o, Matrix.Rotation(math.radians(90), 4, "Z"))  # guard X -> Y; flat normal Y -> -X
    lo, hi = bounds(o)
    zg = widest_slice_z(o, 1)
    print("sword length", hi.z - lo.z, "guard z", zg)
    centre_xy_on_axis(o, 0.0, max(0.02, zg * 0.8))
    # the blade must not be sideways: check the thickness (x) is the smaller of x/y at the blade midpoint
    return o, zg


def mat_assign(obj, mat):
    obj.data.materials.clear()
    obj.data.materials.append(mat)


def run_cos_sword():
    o, zg = build_cos_sword()
    mat_assign(o, cosmos_material("MAT_weapon_real_arming_sword", "MVV_SwordSet_Sword", "T_MVV_SwordSet_8192", 2048))
    lo, hi = bounds(o)
    length = hi.z - lo.z
    grip_z = zg * 0.5
    socks = [add_socket("SOCK_grip_primary", grip_z), add_socket("SOCK_pommel", 0.012), add_socket("SOCK_attach", zg + 0.05),
             add_socket("SOCK_head", length)]
    return export(o, "weapon_real_arming_sword", socks, (8000, 2500, 700), (2048, 1024, 512),
                  {"source": "Cosmos premium MVV SwordSet Sword (photogrammetry)", "licence": "Cosmos DAL (owned)",
                   "scale_applied": SWORD_SCALE, "guard_z_m": round(zg, 3)}), (zg, length)


def run_cos_sword_sheathed(zg, length):
    """Sword drawn home in its leather sheath: the hilt and the sheath show; the blade is inside. Carry sockets sit at the throat."""
    reset()
    sword, zg = build_cos_sword()
    mat_assign(sword, cosmos_material("MAT_weapon_real_arming_sword", "MVV_SwordSet_Sword", "T_MVV_SwordSet_8192", 2048))
    sh = import_fbx(os.path.join(SRC, "MVV_SwordSet_LeatherSheath", "MVV_SwordSet_LeatherSheath", "Meshes", "SM_MVV_LeatherSheath_c0_LOD0.fbx"))
    sh.name = "sheath"
    # sheath: long axis +Z, mouth (the wider, open end) at the top; scaled with the sword
    lo, hi = bounds(sh)
    transform_mesh(sh, Matrix.Scale(SWORD_SCALE, 4))
    lo, hi = bounds(sh)
    ext = hi - lo
    print("sheath ext", ext)
    # mouth is the wider end along its widest horizontal axis
    wide_axis = 0 if ext.x > ext.y else 1
    zw = widest_slice_z(sh, wide_axis)
    if zw > (lo.z + hi.z) / 2:  # wide (mouth) end at the top -> turn it so the mouth is at the bottom, over the guard
        transform_mesh(sh, Matrix.Rotation(math.pi, 4, "X"))
    lo, hi = bounds(sh)
    transform_mesh(sh, Matrix.Translation((0, 0, -lo.z)))
    # the sheath's broad axis must lie along the sword's guard (Y): its wide axis is x now -> turn onto Y
    ext = bounds(sh)[1] - bounds(sh)[0]
    if ext.x > ext.y:
        transform_mesh(sh, Matrix.Rotation(math.radians(90), 4, "Z"))
    shlo, shhi = bounds(sh)
    sh_len = shhi.z - shlo.z
    # sheath mouth at the guard: sheath top (z=sh_len) at the sword's guard z; the sheath hangs along the blade
    blade_len = length - zg
    # sheath centre on the blade axis; guard sits at z = zg, so lift the sheath until its mouth is just below the guard
    sheath_lift = zg - 0.012
    centre_xy_on_axis(sh, 0, sh_len)
    transform_mesh(sh, Matrix.Translation((0, 0, sheath_lift)))
    # sheathed pose: the whole assembly is the sword's frame, so the grip socket and the carry sockets share its origin
    mat_assign(sh, cosmos_material("MAT_weapon_real_sword_sheath", "MVV_SwordSet_LeatherSheath", "T_MVV_SwordSet_8192", 2048))
    both = join_meshes("weapon_real_arming_sword_sheathed", [sword, sh])
    lo, hi = bounds(both)
    socks = [add_socket("SOCK_grip_primary", zg * 0.5), add_socket("SOCK_attach", zg + 0.02),
             add_socket("SOCK_carry_hip", zg + 0.05)]
    return export(both, "weapon_real_arming_sword_sheathed", socks, (11000, 3500, 900), (2048, 1024, 512),
                  {"source": "Cosmos premium MVV SwordSet Sword + Leather Sheath (photogrammetry)", "licence": "Cosmos DAL (owned)",
                   "scale_applied": SWORD_SCALE, "note": "assembly: sword drawn home in the sheath; hang from SOCK_carry_hip at the scabbard throat"})


