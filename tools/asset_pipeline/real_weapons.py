def import_gltf(path):
    """Poly Haven glTFs reference textures/ beside the file but ship them flat: stage a copy with the layout the glTF expects."""
    import shutil
    src = os.path.dirname(path)
    stage = os.path.join(os.environ.get("RW_STAGE", r"D:\Otherreach_Scratch\weapons\work\ph_stage"), os.path.basename(src))
    os.makedirs(os.path.join(stage, "textures"), exist_ok=True)
