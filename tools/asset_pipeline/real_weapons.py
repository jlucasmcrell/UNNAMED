def tube(bm, rings, segs=12):
    """rings: list of (z, rx, ry, cx, cy). A closed lofted tube; returns the loops."""
    loops = []
    for z, rx, ry, cx, cy in rings:
        loop = []
        for i in range(segs):
            a = 2 * math.pi * i / segs
            loop.append(bm.verts.new((cx + rx * math.cos(a), cy + ry * math.sin(a), z)))
        loops.append(loop)
    for a, b in zip(loops, loops[1:]):
        for i in range(segs):
            j = (i + 1) % segs
            bm.faces.new((a[i], a[j], b[j], b[i]))
    return loops


def cap(bm, loop, flip=False):
    c = Vector((sum(v.co.x for v in loop) / len(loop), sum(v.co.y for v in loop) / len(loop), loop[0].co.z))
    cv = bm.verts.new(c)
    for i in range(len(loop)):
        j = (i + 1) % len(loop)
        bm.faces.new((cv, loop[j], loop[i]) if flip else (cv, loop[i], loop[j]))


def uv_cylinder(bm, loops_count, segs, v_scale=1.0, u_scale=1.0):
    uv = bm.loops.layers.uv.verify()
    for f in bm.faces:
        for l in f.loops:
            v = l.vert.co
            ang = math.atan2(v.y, v.x)
            l[uv].uv = ((ang / (2 * math.pi) + 0.5) * u_scale, v.z * v_scale)


def object_from_bm(bm, name, mat):
    bm.normal_update()
    me = bpy.data.meshes.new(name)
    bm.to_mesh(me)
    bm.free()
    ob = bpy.data.objects.new(name, me)
    bpy.context.scene.collection.objects.link(ob)
    me.materials.append(mat)
    for p in me.polygons:
        p.use_smooth = True
    return ob


def box_uv(ob, scale):
    """Simple box-projected UVs (for the leaf head, tapered limbs): u along the longest axis, v around."""
    me = ob.data
    uv = me.uv_layers.new(name="UVMap") if not me.uv_layers else me.uv_layers[0]
    for poly in me.polygons:
        for li in poly.loop_indices:
            co = me.vertices[me.loops[li].vertex_index].co
            uv.data[li].uv = (co.x * scale + co.y * scale, co.z * scale)


def run_spear():
    """Hunting/boar spear: ash shaft ~2.05 m (30 mm tapering to 26 mm at the head), forged leaf head 0.30 m on a 0.12 m socket,
    leather grip wrap, iron ferrule on the butt. Hung/held by SOCK_grip_primary (rear hand) and SOCK_grip_secondary."""
    reset()
    wood = ph_tex("rough_wood", 2048, uv_scale=(1.0, 4.0), tint=(1.0, 0.80, 0.55, 1))
    iron = plain_pbr("MAT_forged_iron", (0.58, 0.58, 0.60, 1), 0.25, 0.48)
    leather = ph_tex("brown_leather", 1024, uv_scale=(2.0, 2.0))
    # shaft
    shaft_len = 2.00
    bm = bmesh.new()
    rings = [(0.02, 0.0125, 0.0125, 0, 0), (0.03, 0.0145, 0.0145, 0, 0)]
    n = 20
    for i in range(n + 1):
        z = 0.03 + (shaft_len - 0.03) * i / n
        t = i / n
        r = 0.0148 - 0.0022 * t + 0.0004 * math.sin(t * 9)  # slight natural variation, 30 -> 25 mm
        rings.append((z, r, r * 0.985, 0.0007 * math.sin(t * 5), 0))
    loops = tube(bm, rings, 14)
    cap(bm, loops[0], True)
    uv_cylinder(bm, 0, 14, 1.2, 2.0)
    shaft = object_from_bm(bm, "spear_shaft", wood)
    # iron ferrule at the butt
    bm = bmesh.new()
    rings = [(0.0, 0.0125, 0.0125, 0, 0), (0.0, 0.0150, 0.0150, 0, 0), (0.07, 0.0150, 0.0150, 0, 0), (0.075, 0.0142, 0.0142, 0, 0)]
    loops = tube(bm, rings, 14)
    cap(bm, loops[0], True)
    uv_cylinder(bm, 0, 14, 3.0, 1.0)
    ferrule = object_from_bm(bm, "spear_ferrule", iron)
    # leather grip wrap (rear hand): 0.34-0.62 m up
    bm = bmesh.new()
    rings = [(0.60 + 0.28 * i / 8, 0.0165, 0.0165, 0, 0) for i in range(9)]
    rings[0] = (rings[0][0], 0.0155, 0.0155, 0, 0)
    rings[-1] = (rings[-1][0], 0.0155, 0.0155, 0, 0)
    loops = tube(bm, rings, 14)
    cap(bm, loops[0], True)
    cap(bm, loops[-1])
    uv_cylinder(bm, 0, 14, 6.0, 3.0)
    wrap = object_from_bm(bm, "spear_wrap", leather)
    # forged head: socket (hollow-looking tube) flowing into a leaf blade with a raised midrib (diamond section)
    top = shaft_len
    bm = bmesh.new()
    sock_rings = [(top - 0.10, 0.0165, 0.0165, 0, 0), (top - 0.09, 0.0185, 0.0185, 0, 0), (top + 0.01, 0.0170, 0.0170, 0, 0),
                  (top + 0.03, 0.0150, 0.0150, 0, 0)]
    loops = tube(bm, sock_rings, 14)
    cap(bm, loops[0], True)
    uv_cylinder(bm, 0, 14, 4.0, 1.0)
    sock = object_from_bm(bm, "spear_socket", iron)
    # blade: leaf outline half-widths along z (0 at socket top to 0 at the tip); diamond section thickness 7 mm at the midrib
    bm = bmesh.new()
    stations = 22
    blade_len = 0.28
    z0 = top + 0.025
    prof = []
    for i in range(stations + 1):
        t = i / stations
        w = 0.0285 * math.sin(math.pi * t ** 0.72) if t < 1 else 0.0  # leaf: widest ~40 % up, long tapering point
        w = max(w, 0.0140 * (1 - t) ** 2, 0.0015) if t < 1 else 0.0
        th = 0.0035 * (1 - t ** 1.6) + 0.0006
        prof.append((z0 + blade_len * t, w, th))
    rows = []
    for z, w, th in prof:
        row = [bm.verts.new((th, 0, z)), bm.verts.new((0, w, z)), bm.verts.new((-th, 0, z)), bm.verts.new((0, -w, z))]
        rows.append(row)
    for a, b in zip(rows, rows[1:]):
        for i in range(4):
            j = (i + 1) % 4
            bm.faces.new((a[i], a[j], b[j], b[i]))
    bm.faces.new(rows[0][::-1])
    bm.faces.new(rows[-1])
    blade = object_from_bm(bm, "spear_blade", iron)
    for p in blade.data.polygons:
        p.use_smooth = False  # crisp diamond-section edges
    meshes = [shaft, ferrule, wrap, sock, blade]
    for o in meshes:
        o.select_set(True)
    bpy.context.view_layer.objects.active = shaft
    bpy.ops.object.join()
    sp = bpy.context.view_layer.objects.active
    sp.name = "weapon_real_hunting_spear"
    sp.data.name = "weapon_real_hunting_spear_mesh"
    apply_all(sp)
    lo, hi = bounds(sp)
    total = hi.z - lo.z
    # carry: SOCK_grip_primary rear hand on the wrap, secondary hand a forearm's length forward, balance point for slings
    socks = [add_socket("SOCK_grip_primary", 0.74), add_socket("SOCK_grip_secondary", 1.30), add_socket("SOCK_head", total),
             add_socket("SOCK_attach", 1.05)]
    return export(sp, "weapon_real_hunting_spear", socks, (0, 1800, 600), (1024, 512, 256),
                  {"source": "hand-modelled in Blender from real-world proportions (ash shaft, forged leaf head); Poly Haven CC0 textures rough_wood, rusty_metal_02, brown_leather",
                   "licence": "CC0 textures; first-party hand modelling (not generative AI)", "length_m": round(total, 3)})


def run_longbow():
    """Self longbow (yew-like stave), 1.78 m nock to nock, D-section 32 x 24 mm at the grip tapering to 12 mm at the horn nocks,
    braced: string ~0.16 m from the grip, tips swept toward the archer (+Z in the glb frame = blender -Y)."""
    reset()
    wood = ph_tex("medieval_wood", 2048, uv_scale=(1.0, 3.0), tint=(0.95, 0.82, 0.62, 1))
    leather = ph_tex("brown_leather", 1024, uv_scale=(2.0, 2.0))
    cord = ph_tex("fabric_leather_01", 512, uv_scale=(1, 1))
    L = 1.78
    brace = 0.16
    n = 40
    bm = bmesh.new()
    rings = []
    for i in range(n + 1):
        t = i / n  # 0 lower tip .. 1 upper tip
        u = abs(2 * t - 1)  # 0 at the grip .. 1 at the tips
        z = L * t
        # flex of a braced longbow: tips come toward the archer (-Y in blender = +Z in glTF), flat through the handle
        bend = brace * (max(0.0, u - 0.12) / 0.88) ** 2.1
        # D-section: wider than thick, belly toward the archer; thickness tapers through the limbs
        taper = 1.0 - 0.62 * (u ** 1.15)
        rx = 0.0125 * (1.0 if u < 0.1 else taper) + 0.003 * taper  # width across the limb -> glTF x
        ry = (0.0155 * taper) + 0.0025
        rings.append((z, rx, ry, 0.0, -bend))
    loops = tube(bm, rings, 14)
    cap(bm, loops[0], True)
    cap(bm, loops[-1])
    uv_cylinder(bm, 0, 14, 2.0, 1.5)
    stave = object_from_bm(bm, "bow_stave", wood)
    # leather grip wrap, 0.12 m, centred on the handle
    bm = bmesh.new()
    gz0, gz1 = L / 2 - 0.065, L / 2 + 0.065
    rings = [(gz0 + (gz1 - gz0) * i / 6, 0.0215, 0.0185, 0, 0) for i in range(7)]
    rings[0] = (rings[0][0], 0.0195, 0.017, 0, 0)
    rings[-1] = (rings[-1][0], 0.0195, 0.017, 0, 0)
    loops = tube(bm, rings, 14)
    cap(bm, loops[0], True)
    cap(bm, loops[-1])
    uv_cylinder(bm, 0, 14, 8.0, 3.0)
    grip = object_from_bm(bm, "bow_grip", leather)
    # string: a 2.5 mm waxed-linen cord from tip to tip (a thin tube; the nocks hold it)
    bm = bmesh.new()
    tip_off = brace
    top = (0, -tip_off, L)
    bot = (0, -tip_off, 0)
    rings = [(z, 0.0017, 0.0017, 0.0, -tip_off) for z in (0.01 + (L - 0.02) * i / 12 for i in range(13))]
    loops = tube(bm, rings, 6)
    cap(bm, loops[0], True)
    cap(bm, loops[-1])
    uv_cylinder(bm, 0, 6, 1.0, 1.0)
    string = object_from_bm(bm, "bow_string", cord)
    # horn nocks (the string sits in them): short caps on each tip
    bm = bmesh.new()
    nl = []
    for tz in (0.0, L):
        sgn = 1 if tz == 0 else -1
        rings = [(tz + sgn * (0.025 * i / 4), 0.0095 * (1 - 0.15 * i / 4) + 0.0015, 0.0085 * (1 - 0.15 * i / 4) + 0.0015, 0, -brace) for i in range(5)]
        nl.append(rings)
    ob = []
    for rings in nl:
        b2 = bmesh.new()
        lp = tube(b2, rings, 10)
        cap(b2, lp[0], True)
        cap(b2, lp[-1])
        uv_cylinder(b2, 0, 10, 4.0, 1.0)
        ob.append(object_from_bm(b2, "bow_nock", cord))
    bm.free()
    parts = [stave, grip, string] + ob
    for o in parts:
        o.select_set(True)
    bpy.context.view_layer.objects.active = stave
    bpy.ops.object.join()
    bw = bpy.context.view_layer.objects.active
    bw.name = "weapon_real_longbow"
    bw.data.name = "weapon_real_longbow_mesh"
    apply_all(bw)
    # sockets: grip at the handle centre; arrow nock point on the string, an arrow's width above the grip; carry on the back
    socks = [add_socket("SOCK_grip_primary", L / 2), add_socket("SOCK_ammo", L / 2 + 0.09, 0, -brace), add_socket("SOCK_attach", L / 2),
             add_socket("SOCK_head", L)]
    return export(bw, "weapon_real_longbow", socks, (0, 1500, 500), (1024, 512, 256),
                  {"source": "hand-modelled in Blender from real-world proportions (yew self longbow, braced); Poly Haven CC0 textures medieval_wood, brown_leather",
                   "licence": "CC0 textures; first-party hand modelling (not generative AI)", "length_m": L, "brace_height_m": brace})


def run_quiver():
    """A leather back/hip quiver: 0.62 m tall, 0.12 m mouth, with a strap loop and a bundle of 12 fletched arrows (fletching as thin
    flat vanes); origin at the base, mouth +Y."""
    reset()
    leather = ph_tex("brown_leather", 1024, uv_scale=(2.0, 2.0))
    wood = ph_tex("medieval_wood", 1024, uv_scale=(1, 3), tint=(0.95, 0.85, 0.65, 1))
    feather = ph_tex("fabric_leather_02", 512, tint=(0.9, 0.88, 0.8, 1))
    H = 0.60
    bm = bmesh.new()
    rings = []
    for i in range(13):
        z = H * i / 12
        rr = 0.052 + 0.020 * (i / 12) ** 0.8
        rings.append((z, rr, rr * 0.9, 0, 0))
    loops = tube(bm, rings, 18)
    cap(bm, loops[0], True)
    uv_cylinder(bm, 0, 18, 2.0, 2.0)
    body = object_from_bm(bm, "quiver_body", leather)
    # mouth rim ring
    bm = bmesh.new()
    rings = [(H - 0.012, 0.074, 0.067, 0, 0), (H - 0.012, 0.080, 0.073, 0, 0), (H + 0.01, 0.080, 0.073, 0, 0), (H + 0.01, 0.074, 0.067, 0, 0)]
    loops = tube(bm, rings, 18)
    uv_cylinder(bm, 0, 18, 8.0, 2.0)
    rim = object_from_bm(bm, "quiver_rim", leather)
    parts = [body, rim]
    import random
    random.seed(7)
    for k in range(12):
        a = random.random() * 2 * math.pi
        r = random.random() ** 0.5 * 0.045
        cx, cy = r * math.cos(a), r * math.sin(a) * 0.9
        h0 = H - 0.05 + random.random() * 0.0
        top = H + 0.16 + random.random() * 0.06
        bm = bmesh.new()
        rr = [(h0 - 0.10, 0.0042, 0.0042, cx, cy), (top, 0.0042, 0.0042, cx, cy)]
        lp = tube(bm, rr, 6)
        cap(bm, lp[0], True)
        cap(bm, lp[-1])
        uv_cylinder(bm, 0, 6, 3.0, 1.0)
        parts.append(object_from_bm(bm, "shaft", wood))
        bm = bmesh.new()
        fz0, fz1 = top - 0.015, top - 0.115
        for ang in (0.0, 120.0, 240.0):
            ca = math.radians(ang + k * 31)
            dx, dy = math.cos(ca), math.sin(ca)
            p = lambda z, d: (cx + dx * d, cy + dy * d, z)
            v = [bm.verts.new(p(fz0, 0.003)), bm.verts.new(p(fz0, 0.017)), bm.verts.new(p(fz1, 0.017)), bm.verts.new(p(fz1, 0.003))]
